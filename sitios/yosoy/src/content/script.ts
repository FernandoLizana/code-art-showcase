export function messagesFor(
  scene: SceneId,
  ctx: { visitedChannels: EntityId[] },
): Message[] {
  switch (scene) {
    case 'first-contact':
      return FIRST_CONTACT
    case 'dispute':
      return DISPUTE
    case 'channel-choice':
      return ctx.visitedChannels.length > 0 ? CHOICE_RETURN : CHOICE
    case 'channel-daat':
      return CHANNEL_DAAT
    case 'channel-bina':
      return CHANNEL_BINA
    case 'channel-keter':
      return CHANNEL_KETER
    case 'channel-yesod':
      return CHANNEL_YESOD
    case 'closing':
      return CLOSING
    default:
      return []
  }
}

export function allMessages(): Message[] {
  return [
    ...FIRST_CONTACT,
    ...DISPUTE,
    ...CHOICE,
    ...CHOICE_RETURN,
    ...CHANNEL_DAAT,
    ...CHANNEL_BINA,
    ...CHANNEL_KETER,
    ...CHANNEL_YESOD,
    ...CLOSING,
  ]
}

export const MESSAGE_BY_ID: Record<string, Message> = Object.fromEntries(
  allMessages().map((message) => [message.id, message]),
)
